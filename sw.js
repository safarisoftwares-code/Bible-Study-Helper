const CACHE_NAME = 'bible-study-helper-v6';
const urlsToCache = [
  './',
  './index.html',
  './manifest.json'
];

// Take over immediately on install — do not wait for old tabs to close
self.addEventListener('install', event => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then(cache => cache.addAll(urlsToCache))
  );
});

// Delete every cache that is not the current one, then claim all open clients
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(
        keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

// Network-first for HTML, cache fallback for everything else.
// The .catch() is the critical fix — a failed fetch no longer rejects the
// respondWith promise and no longer causes "Failed to fetch".
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;

  event.respondWith(
    fetch(event.request)
      .then(response => {
        // Cache successful same-origin responses for offline use
        if (response && response.status === 200 && response.type === 'basic') {
          const copy = response.clone();
          caches.open(CACHE_NAME).then(cache => cache.put(event.request, copy));
        }
        return response;
      })
      .catch(() =>
        caches.match(event.request)
          .then(cached => cached || caches.match('./index.html'))
      )
  );
});